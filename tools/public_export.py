#!/usr/bin/env python3
"""Build a scrubbed public snapshot of this source tree (dry run, local only).

The private working tree contains research material that must never be
published: Samsung packages/APKs and raw reverse-engineering dumps
(``artifacts/``), the upstream checkout (``references/``), internal hand-off
notes with private paths (``CLAUDE.md``, ``WORK.md``, ``RESEARCH.md``,
``docs/RESUME_*``), Samsung UI icons, build outputs and local databases.

This tool copies an explicit allowlist of paths into ``OUT/tree``, overlays
the free icon set from ``desktop/assets-free`` onto
``desktop/public/windows-assets``, scans the result for secrets and private
data, and writes ``OUT/report.json`` + ``OUT/report.md`` (counts and paths
only, never matched values). Unless ``--no-archive`` is given it also writes
``OUT/<name>-src.tar.gz`` and a throwaway local git repository at
``OUT/repo`` with a single commit by a placeholder author. Nothing is pushed
or published.

    python3 tools/public_export.py --out /path/to/scratch/public-export
    python3 tools/public_export.py --out DIR --strict   # exit 1 on blocking findings

Blocking findings: the account e-mail(s) given via --forbid-email (or the
``NOTES_EXPORT_FORBID`` environment variable, comma separated), personal
note titles given via --forbid-term (``NOTES_EXPORT_FORBID_TERMS``), private home
paths, bearer/JWT-like tokens, signed URLs, Samsung UI assets by hash, and
binary executables/packages. Everything else is reported for review.
"""
