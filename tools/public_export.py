def rel(path: Path, base: Path) -> str:
    return path.relative_to(base).as_posix()


# Synthetic SQLite libraries the golden conformance replays (generated test
# data, no user content); exported despite the *.sqlite3 rule and scanned as
# text like any other file.
SYNTHETIC_DATABASES = {
    'crates/notes-engine/conformance/golden/library/main/library.sqlite3',
    'crates/notes-engine/conformance/golden/library/uninit/library.sqlite3',
    'desktop/tests/fixtures/demo-library/library.sqlite3',  # invented demo user for tools/screenshots.mjs
}


def excluded(relpath: str) -> bool:
    if relpath in SYNTHETIC_DATABASES:
        return False
    return any(fnmatch.fnmatch(relpath, g) for g in EXCLUDE_GLOBS)


def public_allowed(relpath: str) -> bool:
    """Single policy predicate: is this source-relative file part of the public tree?

    Also used by tools/export_for_collaborator.sh so both exporters agree."""
    if excluded(relpath) or relpath in EXCLUDED_TESTS:
        return False
    if relpath in TOP_FILES or relpath in EXTRA_FILES:
        return True
    if any(fnmatch.fnmatch(relpath, g) for g in TOP_GLOBS):
        return True
    return any(relpath.startswith(d + '/') for d in TREE_DIRS)


def copy_file(src: Path, dst: Path) -> None:
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst, follow_symlinks=True)


def build_tree(out: Path) -> dict:
    tree = out / 'tree'
    if tree.exists():
        shutil.rmtree(tree)
    tree.mkdir(parents=True)
    copied, skipped, missing = [], [], []
    for name in TOP_FILES:
        src = ROOT / name
        if src.is_file():
            copy_file(src, tree / name); copied.append(name)
        else:
            missing.append(name)
    for d in TREE_DIRS:
        base = ROOT / d
        if not base.is_dir():
            missing.append(d + '/'); continue
        for dirpath, dirnames, filenames in os.walk(base):
            dp = Path(dirpath)
            # prune heavy dirs early
            dirnames[:] = [n for n in dirnames if not excluded(rel(dp / n, ROOT) + '/x')]
            for fn in filenames:
                src = dp / fn
                r = rel(src, ROOT)
                if excluded(r) or r in EXCLUDED_TESTS:
                    skipped.append(r); continue
                if src.is_symlink() and not src.exists():
                    skipped.append(r); continue
                copy_file(src, tree / r); copied.append(r)
    for pattern in TOP_GLOBS:
        for src in sorted(ROOT.glob(pattern)):
            r = rel(src, ROOT)
            if src.is_file() and not excluded(r):
                copy_file(src, tree / r); copied.append(r)
    for r in EXTRA_FILES:
        src = ROOT / r
        if src.is_file():
            copy_file(src, tree / r); copied.append(r)
        else:
            missing.append(r)
    overlays = []
    for src_dir, dst_dir in OVERLAYS:
        s = ROOT / src_dir
        d = tree / dst_dir
        if not s.is_dir():
            missing.append(src_dir + '/ (overlay)'); continue
        d.mkdir(parents=True, exist_ok=True)
        for f in sorted(s.iterdir()):
            if f.is_file():
                copy_file(f, d / f.name); overlays.append(rel(d / f.name, tree))
    return {'tree': tree, 'copied': sorted(set(copied) | set(overlays)), 'skippedInsideAllowed': sorted(skipped),
            'missingOptional': sorted(missing), 'overlaid': overlays}


def samsung_asset_hashes() -> set[str]:
    hashes = set()
    prov = ROOT / 'desktop/windows-assets-provenance.json'
    if prov.is_file():
        for item in json.loads(prov.read_text()):
            if isinstance(item, dict) and item.get('sha256'):
                hashes.add(item['sha256'].lower())
    wa = ROOT / 'desktop/public/windows-assets'
    if wa.is_dir():
        for f in wa.iterdir():
            if f.is_file():
                hashes.add(hashlib.sha256(f.read_bytes()).hexdigest())
    return hashes


def artifact_uuids(limit_bytes: int = 5 * 1024 * 1024) -> set[bytes]:
    """UUIDs seen in account-derived analysis files (never printed)."""
    found: set[bytes] = set()
    base = ROOT / 'artifacts/analysis'
    if not base.is_dir():
        return found
    for dirpath, _, filenames in os.walk(base):
        for fn in filenames:
            if not fn.endswith(('.json', '.md', '.txt', '.jsonl', '.xml')):
                continue
            p = Path(dirpath) / fn
            try:
                if p.stat().st_size > limit_bytes:
                    continue
                found.update(m.lower() for m in UUID.findall(p.read_bytes()))
            except OSError:
                continue
    return found


def scan(tree: Path, forbid_emails: list[bytes], personal_terms: list[bytes]) -> dict:
    asset_hashes = samsung_asset_hashes()
    private_uuids = artifact_uuids()
    # UUIDs that also appear in test fixtures/sources are probably synthetic
    # constants that were copied into analysis files, but still reported.
    findings: dict[str, list] = {k: [] for k in (
        'forbiddenEmail', 'contactOutsideAllowedFiles', 'otherEmail', 'homePath', 'privateStatePath', 'jwt', 'bearerToken', 'signedUrl',
        'sessionId', 'privateKey', 'samsungAssetByHash', 'blockingBinary', 'otherBinary', 'largeFile',
        'decompiledPattern', 'personalTitle', 'uuidSeenInPrivateAnalysis', 'artifactsLink', 'deadDocLink')}
    files = 0
    total_bytes = 0
    for dirpath, _, filenames in os.walk(tree):
        if '/.git' in dirpath:
            continue
        for fn in filenames:
            p = Path(dirpath) / fn
            r = rel(p, tree)
            data = p.read_bytes()
            files += 1
            total_bytes += len(data)
            if hashlib.sha256(data).hexdigest() in asset_hashes:
                findings['samsungAssetByHash'].append(r)
            if len(data) > 1024 * 1024:
                findings['largeFile'].append({'path': r, 'bytes': len(data)})
            kind = next((k for m, k in MAGIC if data.startswith(m)), None)
            if kind and kind != 'gzip':
                blocking = kind in BLOCKING_MAGIC and r not in SYNTHETIC_DATABASES
                (findings['blockingBinary'] if blocking else findings['otherBinary']).append({'path': r, 'type': kind})
                if blocking or (len(data) > TEXT_LIMIT and r not in SYNTHETIC_DATABASES):
                    continue
            if b'\x00' in data[:8192] and not kind:
                findings['otherBinary'].append({'path': r, 'type': 'unknown binary'})
                continue
            if kind == 'gzip':
                try:
                    data = gzip.decompress(data)[:TEXT_LIMIT]
                except (OSError, EOFError):
                    continue
            if len(data) > TEXT_LIMIT:
                continue
            low = data.lower()
            self_file = r == 'tools/public_export.py'  # its own regexes match themselves

            def hit(key: str, count: int) -> None:
                if count:
                    findings[key].append({'path': r, 'count': count})

            hit('forbiddenEmail', sum(low.count(e) for e in forbid_emails))
            hit('contactOutsideAllowedFiles', 0 if self_file else sum(
                low.count(addr) for addr, files_ok in PUBLIC_CONTACTS.items() if r not in files_ok))
            emails = []
            for m in (EMAIL.finditer(data) if b'@' in data else ()):
                e = m.group(0)
                if EMAIL_OK.search(e) or e.lower() in forbid_emails or e.lower() in PUBLIC_CONTACTS or re.search(rb'@\d', e):
                    continue  # placeholders, forbidden (counted above), pkg@1.2.3
                before = data[max(0, m.start() - 8):m.start()]
                if before.endswith((b'//', b':')) or b'://' in before or e.lower().endswith((b'.pdf', b'.png', b'.svg')):
                    continue  # URL userinfo in rejection tests, file names like 0@x.pdf
                emails.append(e)
            hit('otherEmail', len(emails))
            hit('homePath', 0 if self_file else len(HOME_PATH.findall(data)))
            hit('privateStatePath', len(PRIVATE_STATE.findall(data)))
            hit('jwt', len(JWT.findall(data)))
            hit('bearerToken', len(BEARER.findall(data)))
            hit('signedUrl', 0 if self_file else len(SIGNED_URL.findall(data)))
            hit('sessionId', len(SESSION_ID.findall(data)))
            hit('privateKey', 0 if '/synthetic-' in '/' + r.rsplit('/', 1)[-1] or 'synthetic' in r else len(PRIVATE_KEY.findall(data)))
            hit('decompiledPattern', 0 if self_file else len(DECOMPILED.findall(data)))
            if r.endswith('.md'):
                dead = 0
                for target in re.findall(rb'\]\(([^)#\s]+)(?:#[^)]*)?\)', data):
                    t = target.decode('utf-8', 'replace')
                    if '://' in t or t.startswith(('mailto:', '#')):
                        continue
                    if not (p.parent / t).resolve().exists():
                        dead += 1
                hit('deadDocLink', dead)
            hit('artifactsLink', len(re.findall(rb'artifacts/(analysis|android|windows|diagnostics)', data)))
            hit('personalTitle', sum(len(re.findall(rb'\b' + re.escape(t) + rb'\b', data, re.I)) for t in personal_terms))
            if private_uuids:
                hit('uuidSeenInPrivateAnalysis', sum(1 for u in set(m.lower() for m in UUID.findall(data)) if u in private_uuids and len(set(u.replace(b'-', b''))) > 4))
    blocking = ['forbiddenEmail', 'contactOutsideAllowedFiles', 'personalTitle', 'homePath', 'privateStatePath', 'jwt', 'bearerToken', 'signedUrl', 'sessionId',
                'privateKey', 'samsungAssetByHash', 'blockingBinary']
    return {'files': files, 'bytes': total_bytes, 'findings': findings,
            'blockingCategories': blocking,
            'blockingCount': sum(len(findings[k]) for k in blocking),
            'privateUuidReference': len(private_uuids)}


def write_report(out: Path, build: dict, result: dict, archive: dict) -> None:
    top = {}
    for r in build['copied']:
        head = r.split('/', 1)[0] if '/' in r else '(root)'
        top[head] = top.get(head, 0) + 1
    report = {
        'schemaVersion': 1,
        'included': {'files': len(build['copied']), 'byTopLevel': dict(sorted(top.items())),
                     'overlaid': build['overlaid']},
        'excluded': {'insideAllowedDirs': len(build['skippedInsideAllowed']),
                     'insideAllowedDirsSample': build['skippedInsideAllowed'][:200],
                     'documented': DOCUMENTED_EXCLUSIONS},
        'missingOptional': build['missingOptional'],
        'scan': result,
        'archive': archive,
    }
    (out / 'report.json').write_text(json.dumps(report, indent=2, ensure_ascii=False) + '\n')
    lines = ['# Public export dry run', '',
             f"Included files: **{len(build['copied'])}** ({result['bytes']} bytes scanned in {result['files']} files)",
             f"Excluded inside allowed dirs: {len(build['skippedInsideAllowed'])}", '',
             '## Included by top-level path', '']
    lines += [f'- `{k}`: {v}' for k, v in sorted(top.items())]
    lines += ['', '## Not exported (by policy)', '']
    lines += [f'- `{k}` — {v}' for k, v in DOCUMENTED_EXCLUSIONS.items()]
    if build['missingOptional']:
        lines += ['', '## Optional paths not present (yet)', ''] + [f'- `{m}`' for m in build['missingOptional']]
    lines += ['', '## Scan (counts and paths only)', '',
              f"Blocking findings: **{result['blockingCount']}**", '']
    for key, items in result['findings'].items():
        flag = ' (blocking)' if key in result['blockingCategories'] else ''
        lines.append(f'### {key}{flag}: {len(items)}')
        for it in items[:60]:
            if isinstance(it, dict):
                extra = ', '.join(f'{k}={v}' for k, v in it.items() if k != 'path')
                lines.append(f"- `{it['path']}` {extra}")
            else:
                lines.append(f'- `{it}`')
        if len(items) > 60:
            lines.append(f'- … {len(items) - 60} more (see report.json)')
        lines.append('')
    if archive:
        lines += ['## Outputs', ''] + [f'- {k}: `{v}`' for k, v in archive.items()]
    (out / 'report.md').write_text('\n'.join(lines) + '\n')


def make_archive(out: Path, tree: Path, name: str) -> dict:
    tarball = out / f'{name}-src.tar.gz'

    def norm(info: tarfile.TarInfo) -> tarfile.TarInfo:
        info.uid = info.gid = 0
        info.uname = info.gname = ''
        info.mtime = 0
        return info

    with tarfile.open(tarball, 'w:gz') as tar:
        for path in sorted(tree.rglob('*')):
            if path.is_file():
                tar.add(path, arcname=f'{name}/{rel(path, tree)}', filter=norm, recursive=False)
    repo = out / 'repo'
    if repo.exists():
        shutil.rmtree(repo)
    shutil.copytree(tree, repo)
    env = dict(os.environ, GIT_AUTHOR_NAME='Public Export Dry Run', GIT_AUTHOR_EMAIL='dry-run@example.invalid',
               GIT_COMMITTER_NAME='Public Export Dry Run', GIT_COMMITTER_EMAIL='dry-run@example.invalid',
               GIT_CONFIG_NOSYSTEM='1', HOME=str(out))
    git = ['git', '-C', str(repo), '-c', 'init.defaultBranch=main', '-c', 'commit.gpgsign=false']
    subprocess.run(git + ['init', '-q'], check=True, env=env)
    subprocess.run(git + ['add', '-A'], check=True, env=env)
    subprocess.run(git + ['commit', '-q', '-m', 'Initial public snapshot (dry run, not pushed)'], check=True, env=env)
    head = subprocess.run(git + ['rev-parse', 'HEAD'], check=True, env=env, capture_output=True, text=True).stdout.strip()
    return {'tarball': str(tarball), 'tarballSha256': hashlib.sha256(tarball.read_bytes()).hexdigest(),
            'gitRepo': str(repo), 'gitHead': head, 'remote': 'none (never pushed)'}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--forbid-email', action='append', default=[], help='address that must not appear (repeatable)')
    ap.add_argument('--forbid-term', action='append', default=[], help='personal word/title that must not appear (repeatable)')
    ap.add_argument('--no-archive', action='store_true')
    ap.add_argument('--strict', action='store_true', help='exit 1 when blocking findings exist')
    args = ap.parse_args()
    out = args.out.resolve()
    if out == ROOT or ROOT in out.parents:
        print('refusing to export inside the source tree', file=sys.stderr)
        return 2
    out.mkdir(parents=True, exist_ok=True)
    forbid = [e.strip().lower().encode() for e in args.forbid_email + os.environ.get('NOTES_EXPORT_FORBID', '').split(',') if e.strip()]
    if not forbid:
        print('warning: no --forbid-email / NOTES_EXPORT_FORBID given; account e-mail check is generic only', file=sys.stderr)
    terms = [t.strip().encode() for t in args.forbid_term + os.environ.get('NOTES_EXPORT_FORBID_TERMS', '').split(',') if t.strip()]
    build = build_tree(out)
    result = scan(build['tree'], forbid, terms)
    name = json.loads((ROOT / 'branding.json').read_text())['binaryName']
    archive = {} if args.no_archive else make_archive(out, build['tree'], name)
    write_report(out, build, result, archive)
    print(f"included {len(build['copied'])} files; blocking findings: {result['blockingCount']}; report: {out / 'report.md'}")
    return 1 if (args.strict and result['blockingCount']) else 0


if __name__ == '__main__':
    raise SystemExit(main())
